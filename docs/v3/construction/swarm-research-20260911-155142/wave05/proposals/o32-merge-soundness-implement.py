"""Bounded retained-certificate check for the o32 merge-soundness obligation.

Claim under test (finite, non-theoretic): on the inspected restored case
objects, a state-merge cache keyed by exact typed equality of the full
compared poststate - source state, adapter core+journal state and the
reconstructed causal incarnation ledger - stays sound beyond literal action
prefixes: equal merge keys must give equal retained per-prefix verdicts, equal
stored digests and equal observed continuations whenever the same next literal
action was executed.  No performance, reachability or accepted-PASS claim.

Checked premises, each with retained unreduced falsifiers:
  P1 exact key: the key covers only the three components above; literal prefix
     identity and case/unit/outcome labels are deliberately excluded.
  P2 mutation: every retained trace regenerates its typed states by patch
     replay; the rebuilt ledger equals case['incarnation_pairs'] exactly; row,
     event-chain and relation digests agree at each step; done and Q-invocation
     masks bind the executed literal prefix.
  P3 separate regeneration: history (states and ledger) is regenerated by
     replay; journal differences and visible decisions are independently
     recomputed from regenerated states; the common-field relation, envelope
     signatures and pairs_sha256 are NOT recomputed and act as opaque equality
     tokens.
  P4 visible refusals: source-only actions and refused source-attest rows
     never invoked Q; staged identity never establishes incarnation authority.

Finite audit accounting: charge.take(1) is taken once before each inspected
case prefix; audited_prefixes is the exact inspected count, repetitions
included.

Source anchors (unchanged originals; representation only, nothing imported):
  experiments/v3/eight-hour-research-20260910-01a08a22/check.py   audit_case
  experiments/v3/cut-source-overnight/batch-06/adapter_traces.py  trace/restore
  experiments/v3/cut-source-overnight/batch-05/semantic.py        typed/advance
  experiments/v3/cut-source-overnight/batch-07/identity_audit.py  prefix rows
  experiments/v3/cut-source-overnight/s_domain.py                 EXTRA fields
  docs/v3/construction/swarm-research-20260911-155142/inherited/
    remaining-scale-coverage-analysis.md  (refusal labels are not reductions)
"""
import copy
import hashlib
import json

JOURNAL_FIELDS = ('registration', 'attempts', 'append_log', 'append_receipts',
                  'append_reply', 'source_revision', 'collection', 'collected',
                  'attestation', 'staged_source', 'selected_source',
                  'source_generation')
STAGED_RULES = ('strict', 'original-object-identity', 'unrelated')
SOURCE_ONLY = ('register:', 'attempt:', 'atomic:', 'append:', 'collect:',
               'source:')
SOURCE_ONLY_LITERAL = ('append-lose-reply', 'collect-open')
BINDINGS = ('new-binding', 'already-bound', 'binding-conflict', 'unchanged',
            'different-attestation-input')
CASE_FIELDS = ('case', 'unit', 'outcome', 'source', 'adapter', 'rows',
               'incarnation_pairs', 'prefixes')
MAX_FALSIFIERS = 8


def encode(x):
    if isinstance(x, dict):
        return ['dict', [[k, encode(v)] for k, v in sorted(x.items())]]
    if isinstance(x, (list, tuple)):
        return [type(x).__name__, [encode(v) for v in x]]
    return [type(x).__name__, x]


def exact(a, b):
    return encode(a) == encode(b)


def digest(x):
    body = json.dumps(encode(x), sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(body.encode('utf-8')).hexdigest()


def replay(trace):
    state = copy.deepcopy(trace['initial'])
    out = [state]
    for event in trace['events']:
        state = copy.deepcopy(state)
        for key, value in event['patch'].items():
            if trace['side'] == 'adapter' and key in ('core', 'journal'):
                state[key].update(value)
            else:
                state[key] = value
        out.append(state)
    return out


def _result(status, observations, limitations, audited):
    return {'status': status, 'observations': observations,
            'limitations': limitations, 'audited_prefixes': audited}


def inspect_cases(cases, charge):
    falsifiers, limitations, observations = [], [], []

    def falsify(kind, **detail):
        if len(falsifiers) < MAX_FALSIFIERS:
            falsifiers.append(dict(kind=kind, **detail))
        return False

    def check(condition, kind, **detail):
        return bool(condition) or falsify(kind, **detail)

    if charge is None or not hasattr(charge, 'take'):
        return _result('not_applicable', [],
                       ['charge object with take(n) is required'], 0)
    if not isinstance(cases, (list, tuple)) or not cases:
        return _result('not_applicable', [],
                       ['cases must be a nonempty sequence of restored '
                        'run_history/artifact case objects'], 0)

    groups, audited, used, exhausted = {}, 0, 0, False
    for position, case in enumerate(cases):
        if not isinstance(case, dict) or any(k not in case for k in CASE_FIELDS):
            limitations.append('case index %d lacks required certificate fields'
                               % position)
            continue
        used += 1
        name = case['case']
        st, at, rows, prefixes = (case['source'], case['adapter'],
                                  case['rows'], case['prefixes'])
        before = len(falsifiers)
        try:
            ok = check(isinstance(st, dict) and isinstance(at, dict)
                       and st.get('side') == 'source'
                       and at.get('side') == 'adapter', 'trace-sides',
                       case=name)
            actions = st.get('actions') if isinstance(st, dict) else None
            n = len(actions) if isinstance(actions, (list, tuple)) else -1
            ok = check(n >= 0 and list(at.get('actions', ())) == list(actions)
                       and len(st.get('events', ())) == n
                       and len(at.get('events', ())) == n and len(rows) == n
                       and isinstance(prefixes, (list, tuple))
                       and len(prefixes) == n + 1, 'inventory', case=name,
                       expected=n + 1,
                       observed=len(prefixes) if isinstance(prefixes,
                       (list, tuple)) else None) and ok
            if not ok:
                continue
            states_s, states_a = replay(st), replay(at)
            profile = list(st['profile'].get('actions', ()))
            q_actions = list(at['q_profile'].get('actions', ()))
            ledger, ledgers = [], [[]]
            for i in range(n):
                action, verb = actions[i], actions[i].split('@')[0]
                row = rows[i] if isinstance(rows[i], dict) else {}
                ev_s, ev_a = st['events'][i], at['events'][i]
                s1, a1 = states_s[i + 1], states_a[i + 1]
                tag = dict(case=name, prefix=i)
                check(row.get('index') == i and row.get('source_action') == action
                      and row.get('adapter_action') == action, 'row-alignment',
                      expected=[i, action],
                      observed=[row.get('index'), row.get('source_action'),
                                row.get('adapter_action')], **tag)
                check(ev_s.get('action') == action and ev_a.get('action')
                      == action, 'event-alignment', expected=action,
                      observed=[ev_s.get('action'), ev_a.get('action')], **tag)
                check(row.get('source_sha256') == ev_s.get('after_sha256')
                      and row.get('adapter_sha256') == ev_a.get('after_sha256'),
                      'row-event-digest-binding',
                      expected=[ev_s.get('after_sha256'),
                                ev_a.get('after_sha256')],
                      observed=[row.get('source_sha256'),
                                row.get('adapter_sha256')], **tag)
                if i:
                    check(ev_s.get('before_sha256')
                          == st['events'][i - 1].get('after_sha256')
                          and ev_a.get('before_sha256')
                          == at['events'][i - 1].get('after_sha256'),
                          'history-chain-link', **tag)
                want = sum(1 << profile.index(a) for a in actions[:i + 1])
                check(s1.get('done') == want and a1.get('done') == want,
                      'done-mask-binding', expected=want,
                      observed=[s1.get('done'), a1.get('done')], **tag)
                check(a1.get('core', {}).get('done')
                      == sum(1 << q_actions.index(a)
                             for a in a1.get('invocations', ())),
                      'q-invocation-mask', **tag)
                obs_s, obs_a = (row.get('source_observation', {}),
                                row.get('adapter_observation', {}))
                check(obs_s.get('decision') == s1.get('decision')
                      and obs_a.get('decision') == a1.get('decision'),
                      'decision-regeneration',
                      expected=[s1.get('decision'), a1.get('decision')],
                      observed=[obs_s.get('decision'), obs_a.get('decision')],
                      **tag)
                if verb.startswith('append:') or verb == 'append-lose-reply':
                    check(obs_s.get('append_reply') == s1.get('append_reply')
                          and obs_a.get('append_reply')
                          == a1.get('journal', {}).get('append_reply'),
                          'append-reply-regeneration', **tag)
                if verb.startswith(SOURCE_ONLY) or verb in SOURCE_ONLY_LITERAL:
                    check(row.get('q_invoked') is False,
                          'source-only-q-invocation', **tag)
                if verb == 'source-attest' and obs_s.get('decision') != (
                        'source-attest:ok'):
                    check(row.get('q_invoked') is False,
                          'refused-attestation-q-invocation', **tag)
                check(row.get('state_related')
                      == prefixes[i + 1].get('strict_related'),
                      'poststate-relation-binding',
                      expected=prefixes[i + 1].get('strict_related'),
                      observed=row.get('state_related'), **tag)
                check(row.get('prestate_related')
                      == prefixes[i].get('strict_related'),
                      'prestate-relation-binding',
                      expected=prefixes[i].get('strict_related'),
                      observed=row.get('prestate_related'), **tag)
                binding = row.get('binding')
                check(binding in BINDINGS, 'binding-value',
                      expected=list(BINDINGS), observed=binding, **tag)
                if binding == 'new-binding':
                    reason = {'source-attest': 'paired-successful-attestation',
                              'source-restart': 'paired-restart'}.get(verb)
                    check(reason is not None, 'binding-verb', expected=verb,
                          observed=action, **tag)
                    ledger.append({'source': s1.get('source_generation'),
                                   'target': a1.get('core', {}).get(
                                       'source_generation'),
                                   'reason': reason, 'source_event': i,
                                   'target_event': i})
                ledgers.append(copy.deepcopy(ledger))
            check(exact(ledger, case['incarnation_pairs']),
                  'ledger-regeneration', case=name,
                  expected=encode(case['incarnation_pairs']),
                  observed=encode(ledger))
            for i in range(n + 1):
                pr = prefixes[i] if isinstance(prefixes[i], dict) else {}
                tag = dict(case=name, prefix=i)
                check(pr.get('prefix') == i and pr.get('staged_rule')
                      in STAGED_RULES, 'prefix-row-shape',
                      expected=[i, list(STAGED_RULES)],
                      observed=[pr.get('prefix'), pr.get('staged_rule')], **tag)
                check(pr.get('incarnation_pair_established_by_identity')
                      is False, 'identity-creates-authority',
                      expected=False,
                      observed=pr.get(
                          'incarnation_pair_established_by_identity'), **tag)
                proof = pr.get('identity_proof')
                if proof is not None:
                    check(isinstance(proof, dict) and proof.get('case') == name
                          and proof.get('prefix') == i,
                          'identity-proof-binding', expected=[name, i],
                          observed=[proof.get('case') if isinstance(proof,
                          dict) else None, proof.get('prefix') if isinstance(
                          proof, dict) else None], **tag)
        except (KeyError, IndexError, TypeError, ValueError,
                AttributeError) as error:
            falsify('inspection-error', case=name, error=repr(error))
            continue
        if len(falsifiers) != before:
            continue
        for i in range(n + 1):
            try:
                charge.take(1)
            except Exception:
                exhausted = True
                break
            audited += 1
            pr, s1, a1 = prefixes[i], states_s[i], states_a[i]
            journal_diff = [k for k in JOURNAL_FIELDS
                            if not exact(s1.get(k),
                                         a1.get('journal', {}).get(k))]
            check(journal_diff == list(pr.get('differing_journal_fields', ())),
                  'journal-proof-regeneration', case=name, prefix=i,
                  expected=list(pr.get('differing_journal_fields', ())),
                  observed=journal_diff)
            nxt = None
            if i < n:
                row = rows[i]
                nxt = {'action': actions[i], 'outcome':
                       [row.get('q_invoked'), row.get('responses_related'),
                        row.get('state_related'),
                        encode(row.get('source_observation')),
                        encode(row.get('adapter_observation')),
                        row.get('source_sha256'), row.get('adapter_sha256'),
                        row.get('pairs_sha256')]}
            groups.setdefault(digest({'source': s1, 'adapter': a1,
                                      'pairs': ledgers[i]}), []).append({
                'case': name, 'prefix': i, 'literal': list(actions[:i]),
                'verdict': [pr.get('strict_related'), pr.get('related'),
                            list(pr.get('differing_common_fields', ())),
                            list(pr.get('differing_journal_fields', ())),
                            list(pr.get('strict_differing_common_fields',
                                       ())),
                            pr.get('staged_rule'),
                            pr.get('identity_proof') is not None],
                'stored': [st['events'][i - 1].get('after_sha256') if i else
                           None,
                           at['events'][i - 1].get('after_sha256') if i else
                           None,
                           pr.get('pairs_sha256')],
                'next': nxt})
        if exhausted:
            break

    multi = [g for g in groups.values() if len(g) > 1]
    beyond = [g for g in multi
              if len({tuple(e['literal']) for e in g}) > 1]
    for g in multi:
        base = g[0]
        for e in g[1:]:
            tag = dict(case_a=base['case'], prefix_a=base['prefix'],
                       case_b=e['case'], prefix_b=e['prefix'])
            check(e['verdict'] == base['verdict'], 'merge-verdict-divergence',
                  expected=base['verdict'], observed=e['verdict'], **tag)
            check(e['stored'] == base['stored'], 'stored-digest-divergence',
                  expected=base['stored'], observed=e['stored'], **tag)
            if base['next'] and e['next'] and (base['next']['action']
                                             == e['next']['action']):
                check(e['next']['outcome'] == base['next']['outcome'],
                      'continuation-divergence', action=base['next']['action'],
                      expected=base['next']['outcome'],
                      observed=e['next']['outcome'], **tag)

    observations.append({
        'certificate_cases': used, 'merge_groups': len(multi),
        'merged_prefix_positions': sum(len(g) for g in multi),
        'beyond_literal_prefix_groups': len(beyond),
        'largest_merge_group': max((len(g) for g in multi), default=0)})
    for g in beyond[:4]:
        observations.append({'merge_witness': {
            'size': len(g),
            'members': [{'case': e['case'], 'prefix': e['prefix'],
                         'literal_prefix': e['literal']} for e in g[:4]]}})
    for f in falsifiers:
        observations.append(dict(falsifier=f))
    limitations += [
        'bounded evidence over inspected retained certificates only; no '
        'global theorem, no accepted scientific PASS',
        'common-field relation, envelope signatures and pairs_sha256 are '
        'opaque equality tokens; journal differences and decisions are '
        'independently regenerated',
        'continuation determinism is checked only where merged prefixes share '
        'the same next literal action',
        'no performance claim; the key recomputes full typed poststates']
    if falsifiers:
        status = 'counterexample'
    elif exhausted:
        status = 'unproved'
        limitations.append('charge budget exhausted before all retained '
                           'prefixes were inspected')
    elif used == 0:
        status = 'not_applicable'
    elif not beyond:
        status = 'unproved'
        limitations.append('no equal merge keys across distinct literal '
                           'prefixes were retained; the beyond-literal merge '
                           'property was not exercised')
    else:
        status = 'supported'
    return _result(status, observations, limitations, audited)
